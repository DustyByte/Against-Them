"""Cuts M PLUS 1 down to what the Japanese translation uses.

Run after changing the Japanese column of Resources/Translations/strings.csv
(new characters would otherwise show as empty boxes):

    pip install fonttools
    python Tools/subset_japanese_font.py

Reads the full font from Assets/Source/Fonts (not shipped) and writes
Resources/MPLUS1-Japanese.ttf, keeping:
  - every character in the translation's Japanese column,
  - all hiragana, katakana, Japanese punctuation and full-width forms,
  - every kanji the font has (players may use any of them in their names),
  - ASCII, accented Latin letters (Latin-1 and Latin Extended-A, which
    Copperplate mostly lacks), and every weight (it stays a variable font).

It also writes the characters usernames may use, beyond A-Z, 0-9 and _, to
the server (../against-them-server/username_chars.js), so the server accepts
exactly what the game can draw. Deploy the server after running this.
It also trims the font's line height to the em box (ascent 0.88, descent
0.12): M PLUS 1 ships with 1.45 em lines, and next to Copperplate's short
caps lines (0.59 em) every Japanese line came out much taller than English,
pushing dialogs off screen.
"""
import csv
import os
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "Assets", "Source", "Fonts", "MPLUS1-VariableFont_wght.ttf")
CSV = os.path.join(ROOT, "Resources", "Translations", "strings.csv")
OUT = os.path.join(ROOT, "Resources", "MPLUS1-Japanese.ttf")
SERVER_CHARS = os.path.join(os.path.dirname(ROOT), "against-them-server", "username_chars.js")
ALWAYS = "U+0020-007E,U+00C0-017F,U+3000-303F,U+3040-309F,U+30A0-30FF,U+4E00-9FFF,U+FF00-FFEF"
## Letters a username may use besides A-Z, 0-9 and _ (only those the font has).
NAME_RANGES = [
    (0x00C0, 0x00FF),   # Latin-1 letters (minus x and the division sign below)
    (0x0100, 0x017F),   # Latin Extended-A
    (0x3005, 0x3005),   # 々
    (0x3041, 0x3096), (0x309D, 0x309E),   # hiragana
    (0x30A1, 0x30FA), (0x30FC, 0x30FE),   # katakana, ー
    (0x4E00, 0x9FFF),   # kanji
]
NOT_LETTERS = {0x00D7, 0x00F7}

with open(CSV, encoding="utf-8", newline="") as f:
    rows = list(csv.DictReader(f))
text = "".join(row["ja"] for row in rows) + "日本語"

options = subset.Options()
options.layout_features = ["*"]
font = TTFont(SOURCE)
subsetter = subset.Subsetter(options)
subsetter.populate(text=text, unicodes=subset.parse_unicodes(ALWAYS))
subsetter.subset(font)

hhea, os2 = font["hhea"], font["OS/2"]
hhea.ascent, hhea.descent, hhea.lineGap = 880, -120, 0
os2.sTypoAscender, os2.sTypoDescender, os2.sTypoLineGap = 880, -120, 0
os2.usWinAscent, os2.usWinDescent = 880, 120
os2.fsSelection |= 1 << 7   # USE_TYPO_METRICS
font.save(OUT)
print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB,", len(font.getGlyphOrder()), "glyphs")

cmap = font.getBestCmap()
name_chars = "".join(chr(c) for lo, hi in NAME_RANGES for c in range(lo, hi + 1)
                     if c in cmap and c not in NOT_LETTERS)
if os.path.isdir(os.path.dirname(SERVER_CHARS)):
    header = [
        "// Letters usernames may use besides A-Z, 0-9 and _: accented Latin, kana and",
        "// kanji, exactly those the game's fonts can draw. Generated by the game's",
        "// Tools/subset_japanese_font.py; don't edit by hand.",
        "module.exports = '" + name_chars + "';",
    ]
    with open(SERVER_CHARS, "w", encoding="utf-8") as f:
        f.write("\n".join(header) + "\n")
    print("wrote", SERVER_CHARS, len(name_chars), "name letters")
